"""ORM models: the Python representation of the database tables.

Each class maps to one table; each ``Mapped[...]`` attribute maps to one
column. The *authoritative* schema is the Alembic migration in
``migrations/versions/`` (that is what actually runs ``CREATE TABLE``);
these classes must stay in sync with it.

Data model (see docs/DATABASE.md for the full MCD / MLD):

    conversations 1 ──────< N messages
    (a conversation has 0..N messages; a message belongs to exactly 1
     conversation, and is deleted with it: ON DELETE CASCADE)
"""

import uuid
from datetime import datetime

from sqlalchemy import CheckConstraint, DateTime, ForeignKey, Index, Integer, String, Text, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


class Conversation(Base):
    """A chat session between the user and one model."""

    __tablename__ = "conversations"

    # UUID primary key rather than an auto-increment integer: identifiers
    # appear in URLs (/api/conversations/<id>), and sequential integers would
    # let anyone guess other ids (1, 2, 3...). A random UUIDv4 cannot be
    # enumerated. The value is generated by PostgreSQL (gen_random_uuid()).
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    # Model that produced the latest answer. The user can switch models in
    # the middle of a conversation; when no model is chosen explicitly, the
    # conversation continues with this one.
    model: Mapped[str] = mapped_column(String(255), nullable=False)
    # timestamptz = timestamp *with* time zone, stored in UTC by PostgreSQL.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # Python-side navigation (conversation.messages). Not a column.
    # order_by keeps messages in chronological order when loaded.
    messages: Mapped[list["Message"]] = relationship(
        back_populates="conversation",
        order_by="Message.created_at",
        cascade="all, delete-orphan",
        passive_deletes=True,  # let the database's ON DELETE CASCADE do the work
    )

    __table_args__ = (
        # The sidebar lists conversations "most recent first": this index
        # lets PostgreSQL read them already sorted instead of sorting the
        # whole table on every request.
        Index("ix_conversations_updated_at", "updated_at"),
    )


class Message(Base):
    """One message in a conversation, written either by the user or the model."""

    __tablename__ = "messages"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # Foreign key: referential integrity is enforced by PostgreSQL itself.
    # It is impossible to insert a message pointing to a non-existent
    # conversation, and deleting a conversation deletes its messages.
    conversation_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("conversations.id", ondelete="CASCADE"),
        nullable=False,
    )
    role: Mapped[str] = mapped_column(String(16), nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    # Reasoning produced by "thinking" models (assistant messages only).
    thinking: Mapped[str | None] = mapped_column(Text, nullable=True)
    # Model that generated this answer (assistant messages only). Needed
    # because one conversation can mix several models.
    model: Mapped[str | None] = mapped_column(String(255), nullable=True)
    # Generation metrics reported by Ollama (assistant messages only).
    # Useful to measure performance (tokens/s) and the energy cost of usage.
    token_count: Mapped[int | None] = mapped_column(Integer, nullable=True)
    generation_ms: Mapped[int | None] = mapped_column(Integer, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    conversation: Mapped[Conversation] = relationship(back_populates="messages")

    __table_args__ = (
        # Data integrity at the database level: even a buggy client or a
        # manual INSERT cannot store an unknown role.
        CheckConstraint("role IN ('user', 'assistant')", name="ck_messages_role"),
        # Composite index: "all messages of conversation X in chronological
        # order" is the most frequent query in the app.
        Index("ix_messages_conversation_id_created_at", "conversation_id", "created_at"),
    )
