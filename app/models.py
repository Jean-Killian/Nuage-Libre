"""ORM models: the Python representation of the database tables.

Each class maps to one table; each ``Mapped[...]`` attribute maps to one
column. The *authoritative* schema is the Alembic migration in
``migrations/versions/`` (that is what actually runs ``CREATE TABLE``);
these classes must stay in sync with it.

Data model (see docs/DATABASE.md for the full MCD / MLD):

    users 1 ──────< N conversations 1 ──────< N messages

    - a user owns 0..N conversations; a conversation belongs to exactly 1
      user and is deleted with it (ON DELETE CASCADE);
    - a conversation has 0..N messages; a message belongs to exactly 1
      conversation, and is deleted with it (ON DELETE CASCADE).

    users 1 ──────< N files
    - a user owns 0..N files stored in the private cloud. A user who still
      owns files cannot be deleted (ON DELETE RESTRICT): see StoredFile.

    users 1 ──────< N folders 1 ──────< N folders (sub-folders)
                          1 ──────< N files
    - a user owns 0..N folders; a folder sits in 0..1 parent folder of the
      SAME user (none = at the root of the cloud) and contains 0..N
      sub-folders and 0..N files. Folders are purely logical: see Folder.
"""

import uuid
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


class User(Base):
    """A person who owns data in Nuage Libre.

    Deliberately minimal for now: until authentication exists (v0.6) the
    table holds a single row, the "Ghost User" (see app/auth.py). It exists
    already so that ``conversations.user_id`` and ``files.user_id`` are real
    foreign keys from day one: PostgreSQL guarantees every row has a valid
    owner, and adding login later only means adding columns HERE
    (password_hash...), without touching the tables that hold the data.
    """

    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    username: Mapped[str] = mapped_column(String(50), nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    __table_args__ = (
        # Two accounts can never share a login name (enforced by the
        # database itself, whatever the application code does).
        UniqueConstraint("username", name="uq_users_username"),
    )


class Conversation(Base):
    """A chat session between the user and one model."""

    __tablename__ = "conversations"

    # UUID primary key rather than an auto-increment integer: identifiers
    # appear in URLs (/api/conversations/<id>), and sequential integers would
    # let anyone guess other ids (1, 2, 3...). A random UUIDv4 cannot be
    # enumerated. The value is generated by PostgreSQL (gen_random_uuid()).
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # Owner of the conversation. NOT NULL and *without* a default value on
    # purpose ("fail closed"): code that forgets to say who owns a new
    # conversation gets an error, instead of silently giving it to someone.
    # Deleting a user deletes their conversations (and, by cascade, their
    # messages): this is the right to erasure (GDPR art. 17).
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE", name="fk_conversations_user_id_users"),
        nullable=False,
    )
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    # Model that produced the latest answer. The user can switch models in
    # the middle of a conversation; when no model is chosen explicitly, the
    # conversation continues with this one.
    model: Mapped[str] = mapped_column(String(255), nullable=False)
    # timestamptz = timestamp *with* time zone, stored in UTC by PostgreSQL.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # Python-side navigation (conversation.messages). Not a column.
    # order_by keeps messages in chronological order when loaded.
    messages: Mapped[list["Message"]] = relationship(
        back_populates="conversation",
        order_by="Message.created_at",
        cascade="all, delete-orphan",
        passive_deletes=True,  # let the database's ON DELETE CASCADE do the work
    )

    __table_args__ = (
        # The sidebar lists "the conversations of user X, most recent
        # first" (WHERE user_id = ? ORDER BY updated_at DESC). A composite
        # index (user_id, updated_at) answers it directly: PostgreSQL jumps
        # to the user's entries, already sorted by date. It replaces the
        # former index on updated_at alone, which became useless once every
        # query filters by user. user_id comes first, so the same index also
        # serves the foreign key checks when a user is deleted (PostgreSQL
        # does not index foreign keys automatically).
        Index("ix_conversations_user_id_updated_at", "user_id", "updated_at"),
    )


class Message(Base):
    """One message in a conversation, written either by the user or the model."""

    __tablename__ = "messages"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # Foreign key: referential integrity is enforced by PostgreSQL itself.
    # It is impossible to insert a message pointing to a non-existent
    # conversation, and deleting a conversation deletes its messages.
    conversation_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("conversations.id", ondelete="CASCADE"),
        nullable=False,
    )
    role: Mapped[str] = mapped_column(String(16), nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    # Reasoning produced by "thinking" models (assistant messages only).
    thinking: Mapped[str | None] = mapped_column(Text, nullable=True)
    # Model that generated this answer (assistant messages only). Needed
    # because one conversation can mix several models.
    model: Mapped[str | None] = mapped_column(String(255), nullable=True)
    # Generation metrics reported by Ollama (assistant messages only).
    # Useful to measure performance (tokens/s) and the energy cost of usage.
    token_count: Mapped[int | None] = mapped_column(Integer, nullable=True)
    generation_ms: Mapped[int | None] = mapped_column(Integer, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    conversation: Mapped[Conversation] = relationship(back_populates="messages")

    __table_args__ = (
        # Data integrity at the database level: even a buggy client or a
        # manual INSERT cannot store an unknown role.
        CheckConstraint("role IN ('user', 'assistant')", name="ck_messages_role"),
        # Composite index: "all messages of conversation X in chronological
        # order" is the most frequent query in the app.
        Index("ix_messages_conversation_id_created_at", "conversation_id", "created_at"),
    )


class Folder(Base):
    """A folder of the private cloud: a purely LOGICAL container.

    Folders exist only in this table. On disk, every file stays at
    "<user_id>/<file_id>" whatever folder it is shown in (see StoredFile),
    which means:

    - a folder name is never part of a path on disk: no path traversal, no
      characters forbidden by the file system, no length limit of the disk;
    - renaming or moving a folder (future) is one UPDATE of one row, not a
      move of gigabytes on the disk;
    - the security of the storage folder does not change at all.

    The tree is an *adjacency list*: each folder points to its parent
    (``parent_id``), NULL meaning "at the root of the cloud". It is the
    simplest model to keep consistent (one row per folder, nothing to update
    elsewhere when a folder is added), and PostgreSQL walks it with a
    recursive query (WITH RECURSIVE) to build the path of a folder.
    """

    __tablename__ = "folders"

    # Generated in Python (uuid4) by the repository, like files: the object
    # is then complete without being reloaded after the INSERT.
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # Folders are only metadata (no bytes on disk), so deleting a user can
    # safely delete them with CASCADE, like conversations. Files keep their
    # own ON DELETE RESTRICT, which still protects the user's bytes.
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE", name="fk_folders_user_id_users"),
        nullable=False,
    )
    parent_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True)
    # Display name (cleaned, see services/file_policy.py: clean_folder_name).
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    __table_args__ = (
        # (id, user_id) is unique anyway since id is the primary key. Declaring
        # it lets the composite foreign keys below reference the PAIR.
        UniqueConstraint("id", "user_id", name="uq_folders_id_user_id"),
        # Composite foreign key: the parent must be a folder of the SAME
        # user. With a plain "parent_id REFERENCES folders(id)", a buggy or
        # malicious request could hang a folder under someone else's tree;
        # here PostgreSQL itself refuses it, whatever the application does.
        # ON DELETE CASCADE: deleting a folder deletes its sub-folders, but
        # the files they contain stop it (files: ON DELETE RESTRICT), so
        # bytes on disk are never forgotten.
        ForeignKeyConstraint(
            ["parent_id", "user_id"],
            ["folders.id", "folders.user_id"],
            ondelete="CASCADE",
            name="fk_folders_parent_id_folders",
        ),
        # Two folders side by side cannot share a name (like any file
        # system), so a path such as "Courses / 2026" is never ambiguous.
        # NULLS NOT DISTINCT (PostgreSQL 15+): by default NULL values are all
        # "different", so two "Photos" folders at the ROOT (parent_id NULL)
        # would both be accepted. This option treats the root as one place.
        # The constraint's index also answers "sub-folders of X, by name".
        UniqueConstraint(
            "user_id",
            "parent_id",
            "name",
            name="uq_folders_user_id_parent_id_name",
            postgresql_nulls_not_distinct=True,
        ),
        CheckConstraint("name <> ''", name="ck_folders_name_not_empty"),
        # A folder cannot be its own parent (the smallest possible cycle).
        # Longer cycles cannot be created through the API (a folder only
        # gets a parent that already exists, and there is no "move" yet);
        # the recursive path query is bounded anyway (MAX_FOLDER_DEPTH).
        CheckConstraint("parent_id <> id", name="ck_folders_not_own_parent"),
    )


class StoredFile(Base):
    """One file uploaded to the private cloud.

    The row is the *index card* of the file; the bytes themselves live on
    disk, under the storage folder (NUAGE_STORAGE_DIR), at ``file_path``.
    See docs/CLOUD_STORAGE.md for the full life cycle and security model.
    """

    __tablename__ = "files"

    # Generated in Python (uuid4) by the service BEFORE the insert, because
    # the id is also the name of the file on disk, which is written first.
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # ON DELETE RESTRICT (not CASCADE, unlike conversations): a row here is a
    # pointer to a physical file. PostgreSQL cannot delete files on disk, so
    # a cascade would silently "forget" files that still take up space. The
    # database therefore refuses to delete a user who still owns files; the
    # account-deletion service (v0.6) must delete the bytes first.
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="RESTRICT", name="fk_files_user_id_users"),
        nullable=False,
    )
    # Folder the file is shown in; NULL = at the root of the cloud. Only
    # metadata: it does not change where the bytes are stored on disk.
    folder_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True)
    # Display name chosen by the user (cleaned, see services/file_policy.py).
    # It is NEVER used to build a path on disk.
    filename: Mapped[str] = mapped_column(String(255), nullable=False)
    # Location of the bytes RELATIVE to the storage folder, always
    # "<user_id>/<file_id>" (two server-generated UUIDs). Relative, so the
    # storage folder can be moved by changing one setting, and so a value
    # in the database can never designate an arbitrary file of the server.
    file_path: Mapped[str] = mapped_column(String(255), nullable=False)
    # Determined by the server from the file extension, never taken from
    # the client. 255 = RFC 6838 limit (127 for the type + 127 for the subtype).
    mime_type: Mapped[str] = mapped_column(String(255), nullable=False)
    # BIGINT: a 32-bit INTEGER would overflow at 2 GiB.
    size: Mapped[int] = mapped_column(BigInteger, nullable=False)
    # RAG preparation: False = stored in the cloud only; True (v0.7) = its
    # text has been split into chunks and embedded into pgvector, so the AI
    # can use it as context. Integration is a manual, explicit action.
    is_vectorized: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("false"))
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    __table_args__ = (
        # Two rows can never point to the same bytes: deleting one file
        # must never destroy the content of another.
        UniqueConstraint("file_path", name="uq_files_file_path"),
        # Defence in depth against path traversal, at the database level:
        # even a row inserted by hand cannot hold an absolute path or "..".
        # (left()/strpos() rather than LIKE '%..%': no "%" to escape in DDL.)
        CheckConstraint(
            "left(file_path, 1) <> '/' AND strpos(file_path, '..') = 0", name="ck_files_path_relative"
        ),
        CheckConstraint("size >= 0", name="ck_files_size_not_negative"),
        CheckConstraint("filename <> ''", name="ck_files_filename_not_empty"),
        # The folder must belong to the file's owner (composite foreign key,
        # same reasoning as fk_folders_parent_id_folders). ON DELETE
        # RESTRICT: a folder that still holds files cannot be deleted,
        # because its rows point to bytes PostgreSQL cannot delete.
        ForeignKeyConstraint(
            ["folder_id", "user_id"],
            ["folders.id", "folders.user_id"],
            ondelete="RESTRICT",
            name="fk_files_folder_id_folders",
        ),
        # The file manager lists "the files of user X in folder Y, newest
        # first". This index answers it directly. It replaces the former
        # (user_id, created_at) index: user_id still comes first, so it also
        # serves the foreign key checks when a user or a folder is deleted.
        Index("ix_files_user_id_folder_id_created_at", "user_id", "folder_id", "created_at"),
    )
