"""Physical storage of the cloud files on the server's disk.

This class is to the disk what a repository is to the database: the ONLY
code of the application that reads, writes or deletes files under the
storage folder (NUAGE_STORAGE_DIR). It knows nothing about users, HTTP or
business rules; it just stores and returns bytes at relative paths.

Layout on disk
--------------
::

    <storage root>/                          (mode 700: owner only)
        <user_id>/                           (mode 700)
            <file_id>                        (mode 600) the bytes, no extension
            .<file_id>.part                  only while an upload is in progress

Both names are UUIDs generated by the server. The name chosen by the user
("Holiday photo.jpg") is only stored in the database (``files.filename``)
and is NEVER part of a path: it cannot contain "../", cannot overwrite
another file, cannot be a reserved name. This is the first and strongest
protection against path traversal.

Atomic, durable writes
----------------------
An upload is written to ``.<file_id>.part``, flushed to the physical disk
(``fsync``), then renamed to ``<file_id>`` with ``os.replace``. On the same
filesystem a rename is atomic: the final name either does not exist or
points to the complete file, never to half a file (power cut, client that
disconnects, disk full...). On any error the partial file is deleted.

Never blocking the event loop
-----------------------------
FastAPI serves every request from one event loop: a system call that waits
for the disk would freeze ALL requests meanwhile (chat streams included).
Disk operations of the async methods therefore run in a worker thread
(``anyio.to_thread.run_sync``). The single exception is ``delete()``, used
for clean-up after an error: it stays synchronous on purpose, because an
``await`` inside an error handler can itself be interrupted (task
cancellation) and would leave the file behind. Unlinking is a single,
instant metadata operation.
"""

import functools
import os
import shutil
import uuid
from collections.abc import AsyncIterable
from pathlib import Path

import anyio
import anyio.to_thread

# Owner-only permissions: rw------- for files, rwx------ for folders. The
# files are private: other accounts of the server cannot read them.
FILE_MODE = 0o600
DIR_MODE = 0o700

# Network chunks can be small (a few KiB). Each disk write runs in a worker
# thread (to keep the event loop free), so chunks are grouped into 1 MiB
# writes: far fewer thread hops, for a fixed memory cost per upload.
WRITE_BUFFER_SIZE = 1024 * 1024


class UnsafePathError(Exception):
    """A relative path would resolve outside the storage folder."""


def _create_private_file(path: str, flags: int) -> int:
    """``opener`` for open(): create the file with mode 600 directly.

    ``open(..., "xb")`` already adds O_CREAT | O_EXCL: the call fails if the
    path exists, including when it is a (malicious) symbolic link, so the
    write can never be redirected to another file.
    """
    return os.open(path, flags, FILE_MODE)


def _fsync_directory(path: Path) -> None:
    """Flush a directory entry to disk, so a completed rename survives a crash."""
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


class FileStorage:
    def __init__(self, root: Path) -> None:
        # resolve(): absolute, canonical path, symbolic links resolved, so
        # the containment check in resolve() compares like with like.
        self.root = root.resolve()

    @staticmethod
    def relative_path_for(user_id: uuid.UUID, file_id: uuid.UUID) -> str:
        """The only way a storage path is ever built: two server-side UUIDs."""
        return f"{user_id}/{file_id}"

    def resolve(self, relative_path: str) -> Path:
        """Absolute path of a stored file, guaranteed to be INSIDE the root.

        Defence in depth: paths come from our own database and are always
        "<uuid>/<uuid>", but if a row were ever altered (bug, manual SQL
        edit, compromised database), this check stops the download route
        from serving a system file such as /etc/shadow (the "confused
        deputy" problem):

        - ``root / "/etc/passwd"`` gives "/etc/passwd" (an absolute part
          replaces the root) -> outside -> refused;
        - ``"../../etc/passwd"`` is normalised by resolve() -> outside -> refused;
        - a symbolic link inside the folder pointing elsewhere is followed
          by resolve() -> its real target is outside -> refused.
        """
        candidate = (self.root / relative_path).resolve()
        if candidate == self.root or not candidate.is_relative_to(self.root):
            raise UnsafePathError(relative_path)
        return candidate

    def _locate_sync(self, relative_path: str) -> Path | None:
        path = self.resolve(relative_path)
        return path if path.is_file() else None

    async def locate(self, relative_path: str) -> Path | None:
        """Absolute path of a stored file if its bytes are on disk, else None.

        Raises UnsafePathError if the path would leave the storage folder.
        """
        return await anyio.to_thread.run_sync(self._locate_sync, relative_path)

    def _free_bytes_sync(self) -> int:
        probe = self.root
        while not probe.exists():
            probe = probe.parent
        return shutil.disk_usage(probe).free

    async def free_bytes(self) -> int:
        """Free space, in bytes, on the disk that holds the storage folder.

        Measured on the nearest existing folder, so this works (without
        side effects) before the very first upload has created the root.
        """
        return await anyio.to_thread.run_sync(self._free_bytes_sync)

    async def save(self, relative_path: str, chunks: AsyncIterable[bytes]) -> int:
        """Stream ``chunks`` to ``relative_path`` atomically; return the bytes written.

        The content is never held in memory as a whole: at most
        WRITE_BUFFER_SIZE bytes are buffered at any time, whatever the size
        of the file. If ``chunks`` raises (client disconnected, size limit
        exceeded...), nothing is left on disk and the error propagates.
        """
        final = await anyio.to_thread.run_sync(self.resolve, relative_path)
        await anyio.to_thread.run_sync(
            functools.partial(final.parent.mkdir, mode=DIR_MODE, parents=True, exist_ok=True)
        )
        partial = final.with_name(f".{final.name}.part")  # pure string operation, no I/O
        written = 0
        try:
            async with await anyio.open_file(partial, "xb", opener=_create_private_file) as out:
                buffer = bytearray()
                async for chunk in chunks:
                    buffer += chunk
                    if len(buffer) >= WRITE_BUFFER_SIZE:
                        await out.write(bytes(buffer))
                        written += len(buffer)
                        buffer.clear()
                if buffer:
                    await out.write(bytes(buffer))
                    written += len(buffer)
                await out.flush()
                # fsync: the bytes are really on the disk (not only in the
                # OS cache) BEFORE the database says the file exists.
                await anyio.to_thread.run_sync(os.fsync, out.wrapped.fileno())
            await anyio.to_thread.run_sync(os.replace, partial, final)  # atomic rename
            await anyio.to_thread.run_sync(_fsync_directory, final.parent)
        except BaseException:
            # BaseException also covers task cancellation. The clean-up is
            # synchronous on purpose (see module docstring).
            _unlink_quietly(partial)
            _unlink_quietly(final)  # in case the rename had already happened
            raise
        return written

    def delete(self, relative_path: str) -> None:
        """Remove a stored file (no error if it is already gone).

        Synchronous on purpose: it is called from error handlers, where it
        must not be interruptible (see module docstring).
        """
        _unlink_quietly(self.resolve(relative_path))


def _unlink_quietly(path: Path) -> None:
    """Delete ``path`` if it exists (no error if it is already gone)."""
    path.unlink(missing_ok=True)
